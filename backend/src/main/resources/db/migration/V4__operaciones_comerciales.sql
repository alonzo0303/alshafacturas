CREATE UNIQUE INDEX uk_superadmin_correo ON usuarios(correo) WHERE rol = 'SUPERADMIN';
CREATE TABLE productos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empresa_id BIGINT NOT NULL REFERENCES empresas(id), sku VARCHAR(60) NOT NULL,
 nombre VARCHAR(200) NOT NULL, precio NUMERIC(14,2) NOT NULL CHECK(precio > 0),
 stock INTEGER NOT NULL DEFAULT 0 CHECK(stock >= 0), minimo INTEGER NOT NULL DEFAULT 5 CHECK(minimo >= 0),
 activo BOOLEAN NOT NULL DEFAULT TRUE, UNIQUE(empresa_id,sku), UNIQUE(empresa_id,id)
);
CREATE TABLE clientes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empresa_id BIGINT NOT NULL REFERENCES empresas(id), documento VARCHAR(11) NOT NULL,
 nombre VARCHAR(200) NOT NULL, correo VARCHAR(150), direccion VARCHAR(255),
 UNIQUE(empresa_id,documento), UNIQUE(empresa_id,id)
);
CREATE TABLE ventas (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empresa_id BIGINT NOT NULL REFERENCES empresas(id), usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
 cliente_id BIGINT, numero VARCHAR(30) NOT NULL, fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 estado VARCHAR(20) NOT NULL DEFAULT 'CONFIRMADA' CHECK(estado IN ('CONFIRMADA','ANULADA')),
 tipo VARCHAR(20) NOT NULL CHECK(tipo IN ('TICKET','BOLETA','FACTURA')),
 estado_fiscal VARCHAR(40) NOT NULL CHECK(estado_fiscal IN ('NO_APLICA','PENDIENTE_CONFIGURACION')),
 metodo_pago VARCHAR(20) NOT NULL CHECK(metodo_pago IN ('EFECTIVO','TARJETA','TRANSFERENCIA')),
 subtotal NUMERIC(14,2) NOT NULL, igv NUMERIC(14,2) NOT NULL, total NUMERIC(14,2) NOT NULL,
 idempotencia UUID NOT NULL, motivo_anulacion VARCHAR(255),
 UNIQUE(empresa_id,numero), UNIQUE(empresa_id,idempotencia),
 FOREIGN KEY(empresa_id,cliente_id) REFERENCES clientes(empresa_id,id)
);
CREATE TABLE venta_detalles (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 venta_id BIGINT NOT NULL REFERENCES ventas(id), producto_id BIGINT NOT NULL REFERENCES productos(id),
 sku VARCHAR(60) NOT NULL, nombre VARCHAR(200) NOT NULL,
 cantidad INTEGER NOT NULL CHECK(cantidad>0), precio NUMERIC(14,2) NOT NULL CHECK(precio>0), total NUMERIC(14,2) NOT NULL
);
CREATE TABLE compras (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empresa_id BIGINT NOT NULL REFERENCES empresas(id), proveedor VARCHAR(200) NOT NULL, referencia VARCHAR(100) NOT NULL,
 fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, total NUMERIC(14,2) NOT NULL, idempotencia UUID NOT NULL,
 UNIQUE(empresa_id,idempotencia), UNIQUE(empresa_id,proveedor,referencia)
);
CREATE TABLE compra_detalles (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 compra_id BIGINT NOT NULL REFERENCES compras(id), producto_id BIGINT NOT NULL REFERENCES productos(id),
 cantidad INTEGER NOT NULL CHECK(cantidad>0), costo NUMERIC(14,2) NOT NULL CHECK(costo>0)
);
CREATE TABLE movimientos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empresa_id BIGINT NOT NULL REFERENCES empresas(id), producto_id BIGINT NOT NULL,
 usuario_id BIGINT NOT NULL REFERENCES usuarios(id), tipo VARCHAR(20) NOT NULL,
 cantidad INTEGER NOT NULL CHECK(cantidad<>0), saldo INTEGER NOT NULL CHECK(saldo>=0),
 motivo VARCHAR(255) NOT NULL, fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(empresa_id,producto_id) REFERENCES productos(empresa_id,id)
);
CREATE TABLE correlativos (
 empresa_id BIGINT NOT NULL REFERENCES empresas(id), tipo VARCHAR(20) NOT NULL,
 ultimo BIGINT NOT NULL, PRIMARY KEY(empresa_id,tipo)
);
CREATE INDEX ix_ventas_empresa_fecha ON ventas(empresa_id,fecha DESC);
CREATE INDEX ix_compras_empresa_fecha ON compras(empresa_id,fecha DESC);
CREATE INDEX ix_movimientos_empresa_fecha ON movimientos(empresa_id,fecha DESC);
