ALTER TABLE ventas DROP CONSTRAINT ventas_estado_fiscal_check;
CREATE TABLE comprobantes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empresa_id BIGINT NOT NULL REFERENCES empresas(id), venta_id BIGINT NOT NULL REFERENCES ventas(id),
 ambiente VARCHAR(20) NOT NULL CHECK(ambiente IN ('BETA','PRODUCCION')),
 tipo VARCHAR(2) NOT NULL CHECK(tipo IN ('01','03')), numero VARCHAR(20) NOT NULL,
 nombre_archivo VARCHAR(100) NOT NULL, resumen_id VARCHAR(40),
 xml_firmado BYTEA NOT NULL, resumen_firmado BYTEA, cdr BYTEA,
 estado VARCHAR(30) NOT NULL, ticket VARCHAR(100), codigo VARCHAR(30), mensaje VARCHAR(500),
 creado TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, actualizado TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(empresa_id,venta_id,ambiente), UNIQUE(empresa_id,ambiente,numero), UNIQUE(empresa_id,ambiente,resumen_id)
);
CREATE INDEX ix_comprobantes_empresa ON comprobantes(empresa_id,creado DESC);
