CREATE TABLE caja_movimientos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empresa_id BIGINT NOT NULL,local_id BIGINT NOT NULL,caja_id BIGINT NOT NULL,
 tipo VARCHAR(10) NOT NULL CHECK(tipo IN ('INGRESO','EGRESO')),
 importe NUMERIC(14,2) NOT NULL CHECK(importe>0),motivo VARCHAR(1000) NOT NULL CHECK(length(btrim(motivo))>0),
 usuario_original_id BIGINT NOT NULL,usuario_nombre VARCHAR(150) NOT NULL,
 fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,idempotencia UUID NOT NULL,
 FOREIGN KEY(empresa_id,local_id,caja_id) REFERENCES cajas(empresa_id,local_id,id),
 UNIQUE(empresa_id,idempotencia)
);
CREATE INDEX movimientos_por_caja ON caja_movimientos(empresa_id,local_id,caja_id,id);
CREATE TABLE upgrades_suscripcion (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empresa_id BIGINT NOT NULL REFERENCES empresas(id),pago_id BIGINT NOT NULL REFERENCES pagos_suscripcion(id),
 plan_anterior VARCHAR(20) NOT NULL,plan VARCHAR(20) NOT NULL CHECK(plan IN ('EQUIPO','ILIMITADO')),
 limite_empleados INTEGER NOT NULL,tarifa NUMERIC(10,2) NOT NULL CHECK(tarifa>0),
 importe NUMERIC(10,2) NOT NULL CHECK(importe>=0),desde DATE NOT NULL,hasta DATE NOT NULL CHECK(hasta>=desde),
 referencia VARCHAR(120) NOT NULL CHECK(length(btrim(referencia))>0),registrado_por BIGINT,
 creado TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,idempotencia UUID NOT NULL,
 UNIQUE(empresa_id,idempotencia),UNIQUE(empresa_id,referencia)
);
CREATE INDEX upgrades_por_pago ON upgrades_suscripcion(empresa_id,pago_id,id DESC);
