CREATE TABLE roles_negocio (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empresa_id BIGINT NOT NULL REFERENCES empresas(id), codigo VARCHAR(30) NOT NULL,
 nombre VARCHAR(100) NOT NULL, UNIQUE(empresa_id,codigo)
);
CREATE TABLE permisos_rol (
 rol_id BIGINT NOT NULL REFERENCES roles_negocio(id) ON DELETE CASCADE,
 permiso VARCHAR(40) NOT NULL, PRIMARY KEY(rol_id,permiso)
);
CREATE TABLE pagos_suscripcion (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empresa_id BIGINT NOT NULL REFERENCES empresas(id), plan VARCHAR(20) NOT NULL CHECK(plan IN ('INICIO','EQUIPO','ILIMITADO')),
 importe NUMERIC(10,2) NOT NULL CHECK(importe IN (35,50,70)),
 desde DATE NOT NULL, hasta DATE NOT NULL CHECK(hasta>=desde),
 referencia VARCHAR(120) NOT NULL, registrado_por BIGINT NOT NULL REFERENCES usuarios(id),
 creado TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(empresa_id,referencia)
);
CREATE INDEX ix_pago_periodo ON pagos_suscripcion(empresa_id,desde,hasta);

CREATE UNIQUE INDEX roles_negocio_nombre_unique ON roles_negocio (empresa_id, lower(nombre));
